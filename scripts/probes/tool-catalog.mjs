import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const root=path.join(process.env.LOCALAPPDATA,'Programs/DeepSeek Harness/resources/app.asar/dsh/node_modules/@deepseek-ai');
const load=name=>import(pathToFileURL(path.join(root,name,'lib/index.js')).href);
const {Context}=await load('cordis');
const {SystemPrompt}=await load('dsh-system-prompt');
const {ToolRuntime}=await load('dsh-tools');
const {createScope}=await load('dsh-scope');
const ctx=new Context();new SystemPrompt(ctx,{includeHarnessIdentity:false});
const tools=new ToolRuntime(ctx,{mode:'native'});
const definition=name=>({name,description:'Synthetic catalog-only fixture',parameters:{type:'object',properties:{}},output:{schema:{type:'string'},render:()=>[]},execute:()=>{throw Error('Must never execute');}});
const removeGlobal=tools.register(definition('synthetic_global'));
assert.deepEqual(tools.schemas().map(t=>t.name),['synthetic_global']);
const key={};const scoped=createScope(ctx,key);
const removeScoped=scoped.ctx.tools.register(definition('synthetic_scoped'));
assert.deepEqual(tools.schemas(key).map(t=>t.name),['synthetic_global','synthetic_scoped']);
const lift=scoped.ctx.tools.restrict({deny:['synthetic_global']});
assert.deepEqual(tools.schemas(key).map(t=>t.name),['synthetic_scoped']);
assert.equal('execute' in tools.schemas(key)[0],false);
removeScoped();assert.equal(tools.schemas(key).length,0);
lift();removeGlobal();await scoped.dispose();
const result={runtime:process.version,global:true,scope:true,restriction:true,unregister:true,metadataOnly:true,toolExecutions:0};
await mkdir('dist/tool-directory',{recursive:true});await writeFile('dist/tool-directory/runtime-probe.json',JSON.stringify(result,null,2));console.log(result);process.exit(0);
